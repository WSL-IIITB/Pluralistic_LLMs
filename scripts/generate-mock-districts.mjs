// Deterministic hash → [0,1)
function h01(str, salt = "") {
  let h = 0x811c9dc5;
  const s = str + "|" + salt;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return ((h >>> 0) % 100000) / 100000;
}

