function clusterFor(stateCode, districtId, name) {
  const primary = PRIMARY[stateCode] ?? "rama";
  const mix = MIX[stateCode];
  if (mix) {
    let acc = 0;
    const r = h01(districtId, "mix");
    for (const m of mix) {
      acc += m.f;
      if (r < acc) return m.c;
    }
  }
  return primary;
}

const seen = new Set();
const specs = [];
for (const f of geo.features) {
  const p = f.properties;
  const stateCode = String(p.st_code ?? "00");
  const name = String(p.district ?? "").trim();
  const dtCode =
    String(p.dt_code ?? "").trim() || name.toLowerCase().replace(/[^a-z0-9]+/g, "-") || "x";
  const districtId = `${stateCode}-${dtCode}`;
  if (seen.has(districtId)) continue;
  seen.add(districtId);

  const clusterId = clusterFor(stateCode, districtId, name);

  const isMetro = METROS.has(name);
  const base = isMetro ? 55 : 14;
  const jitter = Math.round(h01(districtId, "vol") * (isMetro ? 45 : 30));
  const volume = base + jitter;

  // A minority of low-signal districts fall back to their state aggregate.
  const rFall = h01(districtId, "fall");
  const isStateFallback = !isMetro && rFall > 0.86;

  let confidence;
  if (isStateFallback) confidence = "low";
  else if (isMetro || volume > 55) confidence = "high";
  else if (volume > 28) confidence = "medium";
  else confidence = h01(districtId, "conf") > 0.5 ? "medium" : "low";

  const method = isStateFallback
    ? "state_fallback"
    : isMetro
      ? "city_subreddit"
      : ["place_ner", "script_language", "llm_geolocation"][Math.floor(h01(districtId, "m") * 3)];

  specs.push({
    d: districtId,
    s: stateCode,
    c: clusterId,
    v: volume,
    cf: confidence,
    m: method,
    f: isStateFallback ? 1 : 0,
  });
}

// Order: metros & high-volume first so the map lights up dramatically, then a
// stable-ish spread. We interleave by a hash to avoid state-by-state sweeping.
specs.sort((a, b) => h01(a.d, "ord") - h01(b.d, "ord"));

